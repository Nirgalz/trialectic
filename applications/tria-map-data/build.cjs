/* Build-time only. Runtime assets work from file:// without Node or a server. */
const fs=require('node:fs'),path=require('node:path'),crypto=require('node:crypto');
const Ajv=require('ajv/dist/2020').default;
const standalone=require('ajv/dist/standalone').default;
const esbuild=require('esbuild');
const root=path.resolve(__dirname,'../..'),model=path.join(root,'schemas/model');
const read=p=>JSON.parse(fs.readFileSync(p,'utf8'));
const analysis=read(path.join(model,'analysis.json')),power=read(path.join(model,'power-evaluation.json'));
Object.assign(power.properties,read(path.join(model,'evaluation-context.json')));
analysis.$defs={};power.$defs={};
const inputs=[];
function types(dir){for(const e of fs.readdirSync(dir,{withFileTypes:true}).sort((a,b)=>a.name.localeCompare(b.name))){
 const p=path.join(dir,e.name);if(e.isDirectory())types(p);else if(p.endsWith('.json')){
  Object.assign(path.basename(dir)==='evaluation'?power.$defs:analysis.$defs,read(p));inputs.push(p);
 }
}}
types(path.join(model,'types'));
const ajv=new Ajv({strict:false,allErrors:true,validateFormats:false,code:{source:true}});
ajv.addSchema(power);const validate=ajv.compile(analysis);
const compiled=path.join(__dirname,'.generated-validator.cjs');
fs.writeFileSync(compiled,standalone(ajv,validate));
esbuild.buildSync({entryPoints:[compiled],bundle:true,platform:'browser',format:'iife',globalName:'TriaSchemaValidation',outfile:path.join(__dirname,'schema-validator.js'),minify:true,legalComments:'inline'});
// CJS consumers use the very same bundled validator as the browser.
fs.appendFileSync(path.join(__dirname,'schema-validator.js'),'\nif(typeof module!=="undefined"&&module.exports)module.exports=TriaSchemaValidation;\n');
inputs.push(...['analysis.json','power-evaluation.json','evaluation-context.json'].map(p=>path.join(model,p)));
const hash=crypto.createHash('sha256');for(const p of inputs.sort())hash.update(path.relative(root,p).replaceAll('\\','/')).update(fs.readFileSync(p,'utf8').replace(/\r\n/g,'\n'));
fs.writeFileSync(path.join(__dirname,'schema-manifest.json'),JSON.stringify({source:'schemas/model',sha256:hash.digest('hex'),scope:'Structure only; no empirical or causal validation.'},null,2)+'\n');
const examples={};
for(const [name,file] of Object.entries({'focus-pilot':'applications/triad-graph/examples/focus-pilot.json',generator:'tests/cases/analysis_v2.json',affiliations:'tests/cases/can_affiliations_v22.json',identity:'tests/cases/identity_attribution_v21.json'}))examples[name]=read(path.join(root,file));
const generator=examples.generator;
generator.analysis_id='A-ui-generator-demo';
const branch=structuredClone(generator.scenarios[0]);
Object.assign(branch,{
 id:'S-ui-grid',parent_scenario_id:'S0',
 notes:'UI-only synthetic branch. No inherited assessments or effective events.',
 assumptions:['Hypothesis for UI exploration: battery uncharged, external supply available. No causal result established.']
});
for(const state of branch.states){
 if(state.object.id==='O-battery')state.values.charged=false;
 if(state.object.id==='O-grid')state.values.available=true;
}
generator.scenarios.push(branch);
fs.writeFileSync(path.join(__dirname,'examples.js'),'/* Synthetic fixtures for offline use. Generated by build.cjs. */\n(function(root){const examples='+JSON.stringify(examples)+';if(typeof module!=="undefined"&&module.exports)module.exports=examples;else root.TriaMapExamples=examples;})(globalThis);\n');
const license=fs.readFileSync(require.resolve('ajv/LICENSE'),'utf8');
fs.writeFileSync(path.join(__dirname,'AJV-LICENSE'),license.trimEnd()+'\n');
console.log('Built offline schema validator and synthetic fixtures.');
